"""baseline.py: baseline performance table for the benign workloads (T1.7, extended by T1.8).

Usage:   python3 analysis/baseline.py          (or: make bench)
Runs every workload under Verilator with caches off (ideal 1-cycle memories, the "no cache"
configuration), checks that it self-checks correctly (non-zero exit codes and timeouts fail the
run), and writes docs/baseline.md and analysis/baseline.json.
Per workload: cycles and retired instructions inside the measurement window, CPI, the load-use stall
cycles and flush cycles from the monitor, and the unofficial rates:
  Dhrystone   DMIPS/MHz   = (runs / cycles * 1e6) / 1757        (1757 Dhrystones/s = 1 DMIPS)
  CoreMark    CoreMark/MHz = iterations / cycles * 1e6
Both are labelled unofficial: neither run follows the benchmark's reporting rules (no clock, fixed
iteration count, rv32i with software multiply/divide, -O2, simulation).
Every number comes from a simulation run by this script; nothing is typed in by hand.
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "tests"))
from paths import work_dir          # noqa: E402
from vl_runner import run_image_vl  # noqa: E402

DHRY_RUNS, CM_ITERS = 500, 10


def build(script, out, *args, order="out_first"):
    # build_embench.py and build_workload.py take NAME OUT; the Dhrystone and CoreMark builders take OUT [N]
    argv = [*map(str, args), out] if order == "kernel_first" else [out, *map(str, args)]
    r = subprocess.run([sys.executable, os.path.join(ROOT, "sw", script), *argv], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"build failed ({script}): {(r.stdout + r.stderr)[-500:]}")
    return os.path.join(out, "program.hex")


def workloads():
    """(name, class, hex path, check(result) -> error string or None, rate function(result) -> (label, value) or None)"""
    from workloads import CALIBRATION, HELD_OUT      # tests/workloads.py: the locked registry
    out = []
    for name, kind, arg in CALIBRATION:
        if kind == "dhrystone":
            hexf = build("dhrystone/build_dhrystone.py", work_dir("baseline/dhrystone"), arg)
            out.append((f"Dhrystone ({arg} runs)", "calibration", hexf,
                        lambda r, n=arg: None if f"DHRY_SELFCHECK errors=0 runs={n}" in r["text"] else "self-check failed",
                        lambda r, n=arg: ("DMIPS/MHz (unofficial)", n / r["perf"]["cycles"] * 1e6 / 1757)))
        else:
            hexf = build("coremark/build_coremark.py", work_dir("baseline/coremark"), arg)
            out.append((f"CoreMark ({arg} iterations)", "calibration", hexf,
                        lambda r: None if "[0]crcfinal" in r["text"] else "no CRC output",
                        lambda r, n=arg: ("CoreMark/MHz (unofficial)", n / r["perf"]["cycles"] * 1e6)))
    for name, kind, arg in HELD_OUT:
        if kind == "embench":
            hexf = build("embench/build_embench.py", work_dir(f"baseline/{name}"), arg, order="kernel_first")
        else:
            hexf = build("workloads/build_workload.py", work_dir(f"baseline/{name}"), arg, order="kernel_first")
        out.append((name, "held-out", hexf, lambda r: None, lambda r: None))   # exit code 0 is the self-check
    return out


def main():
    rows = []
    for name, cls, hexf, check, rate in workloads():
        r = run_image_vl(hexf, caches=0, name="baseline_" + name.split()[0].lower(), maxcyc=500_000_000)
        err = None
        if r["timeout"]:
            err = "timeout"
        elif r["halt"] != 0:
            err = f"exit code {r['halt']}"
        else:
            err = check(r)
        if err:
            sys.exit(f"baseline: {name} failed: {err}")
        p = r["perf"]
        lv = rate(r)
        rows.append({"workload": name, "class": cls, "cycles": p["cycles"], "instret": p["instret"],
                     "cpi": p["cycles"] / p["instret"], "stall_loaduse": p["stall_loaduse"],
                     "flush_cycles": p["flush_cycles"], "rate_label": lv[0] if lv else "", "rate": lv[1] if lv else None})
    json.dump(rows, open(os.path.join(HERE, "baseline.json"), "w"), indent=1)
    out = ["# Baseline performance (caches off, no detector)", "",
           "Generated by `analysis/baseline.py` (`make bench`); every number comes from a Verilator run of the",
           "listed program on the pipelined core with ideal 1-cycle memories. Window = the benchmark's timed",
           "region (the MMIO start/stop around it, `tb/sys_monitor.sv`). Columns:", "",
           "- `cycles`, `instret`: cycles and retired instructions in the window; `CPI = cycles / instret`",
           "- `load-use`: cycles the pipeline stalls for a load-use dependency",
           "- `flush`: cycles lost to taken branches and jumps (2 per redirect)", "",
           "| Workload | Class | Cycles | Instr | CPI | Load-use stalls | Flush cycles | Rate |", "|---|---|---|---|---|---|---|---|"]
    for x in rows:
        out.append(f"| {x['workload']} | {x['class']} | {x['cycles']} | {x['instret']} | {x['cpi']:.3f} | "
                   f"{x['stall_loaduse']} | {x['flush_cycles']} | {(x['rate_label'] + ': ' + format(x['rate'], '.3f')) if x['rate'] is not None else 'n/a'} |")
    out += ["", "## How these were produced", "",
            "Exact commands, from the `writehammer/` directory:", "",
            "```",
            "python3 sw/dhrystone/build_dhrystone.py work/baseline/dhrystone 500",
            "python3 sw/coremark/build_coremark.py work/baseline/coremark 10",
            "python3 sw/embench/build_embench.py KERNEL work/baseline/KERNEL      # the 8 kernels of DEC-008",
            "python3 sw/workloads/build_workload.py NAME work/baseline/NAME       # memcpy_big memset_big storeloop",
            "python3 analysis/baseline.py          # or: make bench",
            "```", "",
            "Toolchain: `riscv64-unknown-elf-gcc` 13.4.0, `-march=rv32i_zicsr -mabi=ilp32 -O2` (software multiply and divide",
            "from libgcc: results are rv32i, not rv32im). Simulator: Verilator 5.020. Pinned sources: `docs/TOOLS.md`.", "",
            "## Caveats", "",
            "- The rates are unofficial: fixed iteration counts instead of the benchmarks' timing rules, simulation,",
            "  no clock. Dhrystone/MHz uses 1757 Dhrystones/s per DMIPS; CoreMark/MHz is iterations per cycle x 1e6.",
            "- Every workload self-checks: Dhrystone's own final values; CoreMark's CRCs (also compared with a native",
            "  build in `tests/bench_test.py`); Embench's `verify_benchmark`; the in-repo programs' error counts",
            "  (`tests/workload_test.py` also runs all of them natively). A failing self-check or a timeout stops this",
            "  script instead of printing a number.",
            "- Calibration set: Dhrystone and CoreMark. Held-out set (false-positive evaluation): the rest (DEC-008).",
            "- Caches and write-hammer detectors are not involved here; cache and detector costs are measured from T2 on.", ""]
    open(os.path.join(ROOT, "docs", "baseline.md"), "w").write("\n".join(out))
    print("\n".join(out[10:12 + len(rows)]))


if __name__ == "__main__":
    main()
