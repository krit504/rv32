"""Generate docs/RESULTS.md from the evaluation CSVs only (spec T7.5).

Usage: .venv/bin/python analysis/results_md.py   (or make results)
Inputs: analysis/results.csv, analysis/eval_table_control_compare.csv, docs/HYPOTHESES.md, flow/cost_table.md.
Output: docs/RESULTS.md plus docs/RESULTS.md.json (script, git commit, SHA-256 of every input).
Every number is followed by the CSV file and the run_id (or key) of the row it came from, so it can be
looked up with: grep <run_id> analysis/results.csv. Primary configuration: window 10000, k = 2, 2 KiB D$.
Nothing is typed in by hand.
"""
import hashlib
import json
import re
import subprocess
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
A = ROOT / "analysis"
R = "analysis/results.csv"


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def md(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, row in df.iterrows():
        out.append("| " + " | ".join("" if pd.isna(v) else (f"{v:.4g}" if isinstance(v, float) else str(v)) for v in row) + " |")
    return "\n".join(out)


def label(row):
    d = row["detector"]
    if d in ("D2", "PLACEBO") and pd.notna(row["M"]):
        d += f" M={int(row['M'])}"
    return d + (f" {row['mode']}" if pd.notna(row["mode"]) else "")


def main():
    r = pd.read_csv(A / "results.csv", low_memory=False)
    cc = pd.read_csv(A / "eval_table_control_compare.csv", low_memory=False)
    prim = r[(r.window_cycles == 10000) & (r.threshold_k == 2) & (r.dcache_bytes == 2048) & (r.mem_latency == 20) & (r.line_bytes == 16)].copy()
    prim["arm"] = prim.apply(label, axis=1)
    out = ["# RESULTS (generated by analysis/results_md.py; do not edit by hand)", "",
           f"Source: `{R}` ({len(r)} rows, all with matching architectural signatures: correct = {int((r.correct == 1).sum())}/{len(r)}). "
           "Primary configuration: 2 KiB D$, 16-byte lines, memory latency 20, window 10,000 cycles, k = 2. "
           "Each row names the CSV and run_id it came from.", ""]

    # 1 hypotheses
    hyp = (ROOT / "docs" / "HYPOTHESES.md").read_text()
    rows = re.findall(r"^\| (H[123]) \| (\w+) \|", hyp, re.M)
    out += ["## 1. Hypothesis verdicts (pre-registered criteria, docs/CRITERIA.md)", "",
            "| Hypothesis | Verdict | Source |", "|---|---|---|"]
    out += [f"| {h} | {v} | `docs/HYPOTHESES.md` (generated by `analysis/hypotheses.py` from `{R}`) |" for h, v in rows]
    out.append("")

    # 2 false positives on benign workloads
    ben = prim[prim.workload_class.isin(["held-out", "calibration"]) & prim.detector.isin(["D1", "D2", "D3", "PLACEBO"])]
    t = []
    for arm, g in ben.groupby("arm"):
        w = g.loc[g.fp_cycle_frac.idxmax()]
        t.append({"arm": arm, "benign runs": len(g), "mean fp_cycle_frac": g.fp_cycle_frac.mean(),
                  "max fp_cycle_frac": w.fp_cycle_frac, "worst workload": w.workload, "run_id of max": w.run_id})
    out += ["## 2. False positives on benign workloads (calibration + held-out), primary configuration", "",
            f"From `{R}`, columns `fp_cycle_frac`; one row per arm (D2/PLACEBO per M and mode).", "", md(pd.DataFrame(t)), ""]

    # 3 detection of attacks
    att = prim[(prim.workload_class == "attack") & prim.detector.isin(["D1", "D2", "D3"])]
    t = []
    for arm, g in att.groupby("arm"):
        det = g.detect_latency_cycles.notna()
        t.append({"arm": arm, "attack runs": len(g), "detected": int(det.sum()),
                  "median latency (cycles)": g.detect_latency_cycles.median(),
                  "mean restricted_cycle_frac": g.restricted_cycle_frac.mean()})
    out += ["## 3. Detection of attacks, primary configuration", "",
            f"From `{R}`, columns `detect_latency_cycles` (empty = not detected in the run), `restricted_cycle_frac`; 24 attack runs per arm.", "",
            md(pd.DataFrame(t)), ""]

    # 4 bypass effect: ALWAYS vs NONE on every attack
    base = r[(r.workload_class == "attack") & (r.dcache_bytes == 2048) & (r.mem_latency == 20) & (r.line_bytes == 16)]
    none = base[base.detector == "NONE"].set_index("workload")
    alw = base[base.detector == "ALWAYS"].set_index("workload")
    t = []
    for wl in sorted(set(none.index) & set(alw.index)):
        n, a = none.loc[wl], alw.loc[wl]
        t.append({"attack": wl, "array writes NONE": int(n.array_writes_total), "array writes ALWAYS": int(a.array_writes_total),
                  "ratio": a.array_writes_total / n.array_writes_total, "refills after bypass": int(a.refills_after_bypass),
                  "PMR NONE": n.pmr_all, "PMR ALWAYS": a.pmr_all, "run_id NONE": n.run_id, "run_id ALWAYS": a.run_id})
    tb = pd.DataFrame(t)
    out += ["## 4. Upper bound of the bypass action: ALWAYS (every store restricted) vs NONE on each attack", "",
            f"From `{R}`; `ratio` = array_writes_total ALWAYS / NONE. Mean ratio {tb.ratio.mean():.3f}, median {tb.ratio.median():.3f}, "
            f"minimum {tb.ratio.min():.3f}: bypassing every store removes at most {100 * (1 - tb.ratio.min()):.1f} % of the array writes, "
            "because a bypassed store invalidates its line and the next load refills (and writes) it (`refills after bypass`).", "", md(tb), ""]

    # 5 controls: detector vs placebo
    pc = cc[(cc.window_cycles == 10000) & (cc.threshold_k == 2) & cc.workload_class.eq("attack")]
    t = []
    for (d, m, M), g in pc.groupby(["detector", "mode", "M"], dropna=False):
        t.append({"detector": d, "mode": m, "M": M, "attack runs": len(g), "mean reduction vs NONE": g.detector_reduction_vs_none.mean(),
                  "mean placebo reduction": g.placebo_reduction_vs_none.mean(), "detector beats placebo (runs)": int(g.detector_beats_placebo.sum())})
    out += ["## 5. Detectors against the rate-matched PLACEBO control (attacks, primary configuration)", "",
            "From `analysis/eval_table_control_compare.csv`. A detector that does not beat its placebo is reported as such.", "", md(pd.DataFrame(t)), ""]

    # 6 physical cost
    cost = (ROOT / "flow" / "cost_table.md").read_text()
    table = "\n".join(l for l in cost.splitlines() if l.startswith("|"))
    out += ["## 6. Physical cost (sky130, pinned flow, author-authorized run)", "",
            "Copied from `flow/cost_table.md` (generated by `flow/parse_results.py` from the raw archive `flow/raw.tar.zst`). "
            "Synthesis variation is about 2 % of the cache area: deltas below that are not claims.", "", table, ""]

    path = ROOT / "docs" / "RESULTS.md"
    path.write_text("\n".join(out))
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    (ROOT / "docs" / "RESULTS.md.json").write_text(json.dumps({
        "script": "analysis/results_md.py", "git_commit": commit,
        "inputs_sha256": {p: sha(ROOT / p) for p in (R, "analysis/eval_table_control_compare.csv", "docs/HYPOTHESES.md", "flow/cost_table.md")},
        "output_sha256": sha(path)}, indent=2) + "\n")
    print(f"wrote {path} ({len(out)} blocks)")


if __name__ == "__main__":
    main()
