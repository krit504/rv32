"""Generate T6.3 verdicts from complete measured results, using locked H1-H3.

This script refuses missing runs, incorrect signatures, or missing held-out
false-positive fractions. It does not calibrate or change criteria.
"""
import csv
import hashlib
import json
from pathlib import Path
import statistics
import subprocess

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "analysis/results.csv"
MANIFEST = ROOT / "analysis/matrix_manifest.csv"
OUT = ROOT / "docs/HYPOTHESES.md"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def kind(name):
    return name.split("_", 1)[0].upper()


def evaluate(rows, mode, window, k):
    attacks = sorted({r["workload"] for r in rows if r["workload_class"] == "attack"})
    benign = sorted({r["workload"] for r in rows if r["workload_class"] == "held-out"})
    primary = [r for r in rows if r["icache_bytes"] == "2048" and r["dcache_bytes"] == "2048"]
    def one(name, detector, m=""):
        matches = [r for r in primary if r["workload"] == name and r["detector"] == detector
                   and (detector == "NONE" or (r["mode"] == mode and r["window_cycles"] == str(window)
                   and float(r["threshold_k"]) == k and r["M"] == m))]
        if len(matches) != 1:
            raise ValueError(f"missing/duplicate {name} {detector} {mode} {window} {k} M={m}")
        return matches[0]
    def reduction(name, detector, m=""):
        base, arm = one(name, "NONE"), one(name, detector, m)
        pmr0, pmr1 = float(base["pmr_all"]), float(arm["pmr_all"])
        if pmr0 <= 0:
            raise ValueError(f"invalid baseline PMR for {name}")
        return 1 - pmr1 / pmr0
    d1 = {name: reduction(name, "D1") for name in attacks}
    d2 = {name: reduction(name, "D2", "16") for name in attacks}
    d3 = {name: reduction(name, "D3") for name in attacks}
    fp = {name: float(one(name, "D3")["fp_cycle_frac"]) for name in benign}
    if len(attacks) != 24 or len(benign) < 4:
        raise ValueError("attack or held-out benign coverage incomplete")
    h1 = all((d1[name] >= 0.5 if kind(name) in ("RLA", "RTA") else d1[name] < 0.5)
             for name in attacks)
    # M=16 is the largest pre-registered D2 point within N_lines/8 (128/8).
    # W=16 for both arms, so the counter-flop ratio is 16/128 = 12.5%.
    benefited = [name for name in attacks if d1[name] >= 0.5]
    h2 = (all(d2[name] >= 0.8 * d1[name] for name in benefited)
          if benefited else None)
    h3 = all(d3[name] >= 0.5 for name in attacks) and any(x >= 0.05 for x in fp.values())
    return {"H1": h1, "H2": h2, "H3": h3}, {"D1": d1, "D2_M16": d2, "D3": d3, "D3_heldout_fp": fp}


def main():
    rows = list(csv.DictReader(RESULTS.open()))
    planned = list(csv.DictReader(MANIFEST.open()))
    pids, rids = {r["run_id"] for r in planned}, {r["run_id"] for r in rows}
    if len(rows) != len(planned) or pids != rids or any(r["correct"] != "1" for r in rows):
        raise SystemExit("full correct T6.1 matrix is required before hypothesis verdicts")
    if any(not r["fp_cycle_frac"] for r in rows if r["workload_class"] == "held-out" and r["detector"] == "D3"):
        raise SystemExit("phase-based held-out false-positive fractions are required")
    grids = {}
    for mode in ("STATIC", "ADAPTIVE"):
        for window in (1000, 10000, 100000):
            for k in (1.5, 2.0, 4.0):
                grids[(mode, window, k)] = evaluate(rows, mode, window, k)
    primary = {mode: grids[(mode, 10000, 2.0)] for mode in ("STATIC", "ADAPTIVE")}
    verdicts = {}
    for hid in ("H1", "H2", "H3"):
        primary_values = [primary[m][0][hid] for m in ("STATIC", "ADAPTIVE")]
        sweep_values = [v[0][hid] for v in grids.values()]
        verdicts[hid] = ("INCONCLUSIVE" if None in primary_values + sweep_values
                         or len(set(primary_values + sweep_values)) > 1 else
                         "CONFIRMED" if primary_values[0] else "REFUTED")
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    lines = ["# T6.3 pre-registered hypotheses", "",
             "Generated by `analysis/hypotheses.py` from complete `analysis/results.csv`.",
             f"Results SHA-256: `{sha(RESULTS)}`. Manifest SHA-256: `{sha(MANIFEST)}`. Commit: `{commit}`.",
             "The RLA/RTA/RnLA/RnTA taxonomy is prior work of the author's group (TENDRA and the Write Hammer draft).",
             "Verdicts use exactly `docs/CRITERIA.md` H1–H3; mixed outcomes across the registered modes/windows/thresholds are INCONCLUSIVE.",
             "D2 is evaluated at M=16, the largest registered M within 128/8; its counter-flop ratio is 16/128 = 12.5%.",
             "If D1 reaches no 50% reduction on any attack, H2 is INCONCLUSIVE because its benefit comparison has no eligible attack.",
             "", "| Hypothesis | Verdict | Primary STATIC | Primary ADAPTIVE |", "|---|---|---|---|"]
    for hid in ("H1", "H2", "H3"):
        lines.append(f"| {hid} | {verdicts[hid]} | {primary['STATIC'][0][hid]} | {primary['ADAPTIVE'][0][hid]} |")
    for mode in ("STATIC", "ADAPTIVE"):
        data = primary[mode][1]
        lines += ["", f"## Primary k=2, 10,000 cycles: {mode}", "",
                  "Reductions are relative to NONE PMR for the same image. Random seeds 1–5 appear separately; no change smaller than their range is claimed.",
                  "", "| Attack image | D1 PMR reduction | D2 M=16 reduction | D3 reduction |",
                  "|---|---:|---:|---:|"]
        for name in sorted(data["D1"]):
            lines.append(f"| {name} | {data['D1'][name]:.6f} | {data['D2_M16'][name]:.6f} | {data['D3'][name]:.6f} |")
        lines += ["", "| Attack kind/form | Detector | Mean reduction | Seed range |",
                  "|---|---|---:|---:|"]
        groups = sorted({"_".join(name.split("_")[:2]) for name in data["D1"]})
        for group in groups:
            names = [name for name in data["D1"] if name.startswith(group + "_")]
            for detector in ("D1", "D2_M16", "D3"):
                values = [data[detector][name] for name in names]
                lines.append(f"| {group} | {detector} | {statistics.mean(values):.6f} | "
                             f"{min(values):.6f}–{max(values):.6f} |")
        lines += ["", "| Held-out benign | D3 false-positive cycle fraction |", "|---|---:|"]
        for name, fp in sorted(data["D3_heldout_fp"].items()):
            lines.append(f"| {name} | {fp:.6f} |")
    lines += ["", "## Registered sweep outcomes", "",
              "| Mode | Window cycles | k | H1 condition | H2 condition | H3 condition |",
              "|---|---:|---:|---|---|---|"]
    for (mode, window, k), (values, _) in grids.items():
        lines.append(f"| {mode} | {window} | {k:g} | {values['H1']} | {values['H2']} | {values['H3']} |")
    example = []
    for detector in ("NONE", "D1", "ALWAYS"):
        candidates = [r for r in rows if r["workload"] == "rla_direct_s1"
                      and r["detector"] == detector and r["dcache_bytes"] == "2048"
                      and (detector != "D1" or (r["mode"] == "STATIC"
                           and r["window_cycles"] == "10000" and float(r["threshold_k"]) == 2.0))]
        if len(candidates) != 1:
            raise ValueError(f"missing refill example: {detector}")
        example.append(candidates[0])
    lines += ["", "## Bypass and refill finding", "",
              "A bypassed store invalidates a resident line. A following load refills that line and writes the data array. This measured refill cost explains why bypass-heavy attack loops can retain nearly the same total array writes and PMR. Data-array writes here include fills and stores; metadata writes are excluded.",
              "", "| RLA direct seed 1 | Bypassed stores | Refills after bypass | Array writes | PMR over all lines |",
              "|---|---:|---:|---:|---:|"]
    for r in example:
        lines.append(f"| {r['detector']} | {r['bypassed_stores']} | {r['refills_after_bypass']} | {r['array_writes_total']} | {float(r['pmr_all']):.6f} |")
    crc_sweep = [r for r in rows if r["workload"] == "crc32" and r["detector"] == "D1"
                 and r["dcache_bytes"] == "2048"]
    crc = [r for r in crc_sweep if r["mode"] == "STATIC"
           and r["window_cycles"] == "10000" and float(r["threshold_k"]) == 2.0]
    if len(crc) != 1 or len(crc_sweep) != 18:
        raise ValueError("missing held-out crc32 D1 result")
    crc_flagged = sum(float(r["fp_cycle_frac"]) > 0 for r in crc_sweep)
    crc_max = max(float(r["fp_cycle_frac"]) for r in crc_sweep)
    lines += ["", "## Held-out crc32 finding", "",
              f"The benign `crc32` workload has a measured D1 false-positive cycle fraction of {float(crc[0]['fp_cycle_frac']):.6f} at the primary setting. Across the 18 registered D1 settings, {crc_flagged} restrict at least one cycle and the maximum fraction is {crc_max:.6f}. Its near single-line write concentration is retained as a result (DEC-010); it was neither removed nor used to recalibrate the threshold."]
    lines += ["", "The supplementary windowed PMR, top-k line share and maximum line writes per cycle are **POST-HOC EXPLORATORY** (DEC-010). They do not change T4.7 validation or the pre-registered H1–H3 criteria."]
    OUT.write_text("\n".join(lines) + "\n")
    sidecar = {"script": "analysis/hypotheses.py", "git_commit": commit,
               "script_sha256": sha(Path(__file__)),
               "results_sha256": sha(RESULTS), "manifest_sha256": sha(MANIFEST),
               "criteria_sha256": sha(ROOT / "docs/CRITERIA.md"),
               "document_sha256": sha(OUT), "verdicts": verdicts}
    Path(str(OUT) + ".json").write_text(json.dumps(sidecar, indent=2) + "\n")
    print("hypotheses:", verdicts)


if __name__ == "__main__":
    main()
